#Arithmetic Operators

x = 90
y = 5

print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x % y) #Modulus - returns a reminder after division

#Comparison Operators - compares values and returns boolean

num1 = 45
num2 = 15

print(num1 < num2)
print(num1 > num2)
print(num1 <= num2)
print(num1 >= num2)
print(num1 == num2) #Equal to
print(num1 != num2) #Not equal to


#Assignment Operators - stores values in variables

number = 80
print(number)

#Operator Precedence
number += 2
print(number)

#Logical Operators - and, or, not
print( 100 == 50 and 60 < 80)
print( 100 == 50 or 60 < 80)
print( not(100 == 50 and 60 < 80))



